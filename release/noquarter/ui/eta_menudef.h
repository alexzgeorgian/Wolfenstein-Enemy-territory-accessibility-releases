// The layout macros the accessibility pages are written with. ET: Legacy's
// menudef.h has them; No Quarter's, from Enemy Territory 2.60, does not, so
// the mode's pages bring them. The same values as ET: Legacy's, so a page
// lays out the same in both games.

#define SUBWINDOW_OPTION_X_PADDING        2
#define SUBWINDOW_OPTION_Y_PADDING        4
#define SUBWINDOW_OPTION_Y_START          32
#define SUBWINDOW_OPTION_HEADER_WIDTH_L   (.50 * (WINDOW_WIDTH - 18))
#define SUBWINDOW_OPTION_HEADER_WIDTH_R   (.50 * (WINDOW_WIDTH - 18))
#define SUBWINDOW_OPTION_HEADER_Y_PADDING 4
#define SUBWINDOW_OPTION_WIDTH_L          (SUBWINDOW_OPTION_HEADER_WIDTH_L - SUBWINDOW_OPTION_X_PADDING * 2)
#define SUBWINDOW_OPTION_WIDTH_R          (SUBWINDOW_OPTION_HEADER_WIDTH_R - SUBWINDOW_OPTION_X_PADDING * 2)
#define SUBWINDOW_OPTION_HEIGHT           10

#define SUBWINDOW_OPTION_HEADER_X1_START 6
#define SUBWINDOW_OPTION_X1_START        (SUBWINDOW_OPTION_HEADER_X1_START + SUBWINDOW_OPTION_X_PADDING)
#define SUBWINDOW_OPTION_HEADER_X2_START (SUBWINDOW_OPTION_X1_START + SUBWINDOW_OPTION_WIDTH_L + SUBWINDOW_OPTION_X_PADDING * 4)
#define SUBWINDOW_OPTION_X2_START        (SUBWINDOW_OPTION_HEADER_X2_START + SUBWINDOW_OPTION_X_PADDING)

#define SUBWINDOW_OPTION_COMPUTE_Y(Y, pos) (Y + SUBWINDOW_OPTION_HEADER_Y_PADDING + (SUBWINDOW_OPTION_HEIGHT + 2) * pos)
#define SUBWINDOW_OPTION_COMPUTE_H(pos) (SUBWINDOW_OPTION_HEADER_Y_PADDING + (SUBWINDOW_OPTION_HEIGHT + 2) * (pos + 1))
